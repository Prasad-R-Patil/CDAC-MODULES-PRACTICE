package collections;
import java.util.*;

public class HashSetDemo {
	
	public static void main(String[] args) {
		
		HashSet h = new HashSet();
		
		h.add(10);
		h.add('A');
		h.add(20);
		h.add(20.54f);
		h.add(null);
		
		System.out.println(h.add(2));
		
		System.out.println(h);
		
		
		
		
		
		
		
		
		
	}
}
